#!/usr/bin/env bash
# ---------------------------------------------------------------------------
#  اجرای ویرا از هر جایی داخل مخزن — همتای لینوکسی/مکِ vira.cmd.
#
#  دلیلش همان است: «node src/cli.js» از ریشهٔ مخزن، خطای MODULE_NOT_FOUND می‌دهد
#  که هیچ اشاره‌ای به پوشه ندارد. این اسکریپت خودش جای درست می‌رود.
#
#  کاربرد:  ./vira.sh [گزینه‌ها]
# ---------------------------------------------------------------------------
set -euo pipefail

here="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
app="$here/vira"

if ! command -v node >/dev/null 2>&1; then
	printf '\n  Node.js پیدا نشد. نسخهٔ ۲۰ یا بالاتر لازم است.\n\n' >&2
	exit 1
fi

if [ ! -f "$app/src/cli.js" ]; then
	printf '\n  پوشهٔ vira کنار این فایل نیست: %s\n  این اسکریپت باید در ریشهٔ مخزن بماند.\n\n' "$app" >&2
	exit 1
fi

cd "$app"

# وابستگی‌ها را خودمان نصب نمی‌کنیم — npm ci هر بار وقت کاربر را می‌گرفت.
# فقط اگر واقعاً غایب باشند، سریع و روشن می‌گوییم چه بزند و بیرون می‌آییم.
if [ ! -d node_modules ]; then
	printf '\n  وابستگی‌ها نصب نیستند. یک بار این را بزن:\n\n      cd %s && npm ci\n\n' "$app" >&2
	exit 1
fi

exec node src/cli.js "$@"
